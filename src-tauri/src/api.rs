#[tauri::command]
pub async fn api_download_open_dir(app: tauri::AppHandle) -> Result<(), String> {
    let dir = crate::download::current_dir()?;
    let _ = std::fs::create_dir_all(&dir);
    app.opener()
        .open_path(dir, None::<&str>)
        .map_err(|e| e.to_string())
}

#[tauri::command]
pub async fn api_download_open_file(
    app: tauri::AppHandle,
    id: i64,
    ep: u32,
) -> Result<(), String> {
    let path = crate::download::offline_file_path(id, ep)?
        .ok_or_else(|| "Offline file not found".to_string())?;
    app.opener()
        .open_path(path, None::<&str>)
        .map_err(|e| e.to_string())
}

